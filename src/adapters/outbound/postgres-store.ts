import { randomUUID } from 'node:crypto';
import pg from 'pg';
import type { PoolClient } from 'pg';
import type {
  Job,
  MemoryFragment,
  MemoryMatch,
  PendingMemoryMessage,
} from '../../domain/models.js';
import type { ConversationStore, AuditPort, MemoryRepository } from '../../application/ports.js';

/** PostgreSQL owns durable state. A session lock permits one active assistant per schema. */
export class Store implements ConversationStore, AuditPort, MemoryRepository {
  readonly pool: pg.Pool;
  private lease?: PoolClient;
  private closed = false;
  private constructor(
    url: string,
    readonly dimensions: number,
    schema: string,
  ) {
    if (!Number.isInteger(dimensions) || dimensions < 1 || dimensions > 4000)
      throw new Error('Embedding dimensions must be between 1 and 4000');
    if (!/^[a-z_][a-z0-9_]*$/.test(schema)) throw new Error('Invalid database schema');
    this.pool = new pg.Pool({
      connectionString: url,
      max: 8,
      connectionTimeoutMillis: 5000,
      idleTimeoutMillis: 30000,
      statement_timeout: 15000,
      options: `-c search_path=${schema},public`,
    });
    this.pool.on('error', () =>
      console.error(JSON.stringify({ event: 'database_connection_failed' })),
    );
  }
  static async open(url: string, dimensions: number, schema = 'public'): Promise<Store> {
    const store = new Store(url, dimensions, schema);
    try {
      store.lease = await store.pool.connect();
      const { rows } = await store.lease.query(
        "SELECT pg_try_advisory_lock(hashtextextended(current_database() || ':' || current_schema() || ':assistant',0)) AS acquired",
      );
      if (!rows[0].acquired) throw new Error('Another assistant already owns this database schema');
      // Losing this connection loses the execution lock: terminate before doing more work.
      store.lease.on('error', () => {
        console.error(JSON.stringify({ event: 'database_lease_lost' }));
        process.exit(1);
      });
      await store.initialize();
      return store;
    } catch (error) {
      await store.close();
      throw error;
    }
  }
  private async initialize() {
    const client = this.lease!;
    await client.query('BEGIN');
    try {
      await client.query(`CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;
        CREATE TABLE IF NOT EXISTS schema_version(version INTEGER PRIMARY KEY, dimensions INTEGER NOT NULL);
        CREATE TABLE IF NOT EXISTS jobs(id TEXT PRIMARY KEY, sequence BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
          session TEXT NOT NULL, dedupe TEXT UNIQUE, payload JSONB NOT NULL, status TEXT NOT NULL DEFAULT 'pending',
          output TEXT, error TEXT, created TIMESTAMPTZ NOT NULL DEFAULT now());
        CREATE TABLE IF NOT EXISTS sessions(id TEXT PRIMARY KEY, thread TEXT, history_after BIGINT NOT NULL DEFAULT 0);
        CREATE TABLE IF NOT EXISTS messages(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, session TEXT NOT NULL,
          role TEXT NOT NULL, text TEXT NOT NULL, consolidated INTEGER NOT NULL DEFAULT 0, created TIMESTAMPTZ NOT NULL DEFAULT now());
        CREATE TABLE IF NOT EXISTS memories(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, session TEXT NOT NULL,
          text TEXT NOT NULL, category TEXT NOT NULL, tags JSONB NOT NULL, embedding vector(${this.dimensions}),
          source TEXT UNIQUE, created TIMESTAMPTZ NOT NULL DEFAULT now());
        CREATE TABLE IF NOT EXISTS audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,job TEXT,tool TEXT,
          success INTEGER,duration INTEGER,created TIMESTAMPTZ NOT NULL DEFAULT now());
        CREATE TABLE IF NOT EXISTS schedules(key TEXT PRIMARY KEY,created TIMESTAMPTZ NOT NULL DEFAULT now());
        CREATE TABLE IF NOT EXISTS cursors(name TEXT PRIMARY KEY,value BIGINT NOT NULL);
        CREATE TABLE IF NOT EXISTS imports(key TEXT PRIMARY KEY,created TIMESTAMPTZ NOT NULL DEFAULT now());
        CREATE INDEX IF NOT EXISTS jobs_pending ON jobs(sequence) WHERE status='pending';
        CREATE UNIQUE INDEX IF NOT EXISTS jobs_running_session ON jobs(session) WHERE status='running';
        CREATE INDEX IF NOT EXISTS messages_session ON messages(session,id);
        CREATE INDEX IF NOT EXISTS memories_session ON memories(session,category,created);
        CREATE INDEX IF NOT EXISTS memories_embedding ON memories USING hnsw ((embedding::halfvec(${this.dimensions})) halfvec_cosine_ops);
        INSERT INTO schema_version(version,dimensions) VALUES(1,${this.dimensions}) ON CONFLICT DO NOTHING;`);
      const { rows } = await client.query(
        'SELECT * FROM schema_version ORDER BY version DESC LIMIT 1',
      );
      if (rows[0].version !== 1 || rows[0].dimensions !== this.dimensions)
        throw new Error('Database schema or embedding dimensions do not match configuration');
      await client.query(
        "UPDATE jobs SET status='failed',error='Service stopped during execution; inspect effects before retrying' WHERE status='running'",
      );
      await client.query('COMMIT');
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    }
  }
  private decode(row: any): Job {
    return { ...row, created: row.created.toISOString() };
  }
  async enqueue(session: string, payload: unknown, dedupe: string = randomUUID()): Promise<Job> {
    await this.pool.query(
      'INSERT INTO jobs(id,session,dedupe,payload) VALUES($1,$2,$3,$4) ON CONFLICT(dedupe) DO NOTHING',
      [randomUUID(), session, dedupe, JSON.stringify(payload)],
    );
    return this.decode(
      (await this.pool.query('SELECT * FROM jobs WHERE dedupe=$1', [dedupe])).rows[0],
    );
  }
  async job(id: string): Promise<Job | undefined> {
    const { rows } = await this.pool.query('SELECT * FROM jobs WHERE id=$1', [id]);
    return rows[0] ? this.decode(rows[0]) : undefined;
  }
  async claim(excluded: string[]): Promise<Job | undefined> {
    // Serialize claims as well as using row locks, so concurrent callers cannot claim one session twice.
    const client = await this.pool.connect();
    try {
      await client.query('BEGIN');
      await client.query(
        "SELECT pg_advisory_xact_lock(hashtextextended(current_database() || ':' || current_schema() || ':claim',0))",
      );
      const { rows } = await client.query(
        `WITH next AS (
        SELECT id FROM jobs j WHERE status='pending' AND NOT(session=ANY($1::text[]))
        AND NOT EXISTS(SELECT 1 FROM jobs running WHERE running.session=j.session AND running.status='running')
        ORDER BY sequence FOR UPDATE SKIP LOCKED LIMIT 1)
        UPDATE jobs SET status='running' FROM next WHERE jobs.id=next.id RETURNING jobs.*`,
        [excluded],
      );
      await client.query('COMMIT');
      return rows[0] ? this.decode(rows[0]) : undefined;
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    } finally {
      client.release();
    }
  }
  async finish(id: string, output: string) {
    await this.pool.query("UPDATE jobs SET status='done',output=$2 WHERE id=$1", [id, output]);
  }
  async fail(id: string, error: string) {
    await this.pool.query("UPDATE jobs SET status='failed',error=$2 WHERE id=$1", [id, error]);
  }
  async thread(session: string): Promise<string | undefined> {
    return (await this.pool.query('SELECT thread FROM sessions WHERE id=$1', [session])).rows[0]
      ?.thread;
  }
  async setThread(session: string, thread: string) {
    await this.pool.query(
      'INSERT INTO sessions(id,thread) VALUES($1,$2) ON CONFLICT(id) DO UPDATE SET thread=excluded.thread',
      [session, thread],
    );
  }
  async reset(session?: string) {
    if (session)
      await this.pool.query(
        'INSERT INTO sessions(id,thread,history_after) VALUES($1,NULL,(SELECT COALESCE(MAX(id),0) FROM messages)) ON CONFLICT(id) DO UPDATE SET thread=NULL,history_after=excluded.history_after',
        [session],
      );
    else
      await this.pool.query(
        'UPDATE sessions SET thread=NULL,history_after=(SELECT COALESCE(MAX(id),0) FROM messages)',
      );
  }
  async addMessage(session: string, role: string, text: string) {
    await this.pool.query('INSERT INTO messages(session,role,text) VALUES($1,$2,$3)', [
      session,
      role,
      text,
    ]);
  }
  async history(session: string) {
    return (
      await this.pool.query(
        'SELECT role,text,created FROM messages WHERE session=$1 AND id>COALESCE((SELECT history_after FROM sessions WHERE id=$1),0) ORDER BY id DESC LIMIT 40',
        [session],
      )
    ).rows.reverse();
  }
  async audit(job: string, tool: string, success: boolean, duration: number) {
    await this.pool.query('INSERT INTO audit(job,tool,success,duration) VALUES($1,$2,$3,$4)', [
      job,
      tool,
      +success,
      duration,
    ]);
  }
  async scheduled(key: string) {
    return !!(await this.pool.query('SELECT 1 FROM schedules WHERE key=$1', [key])).rowCount;
  }
  async markScheduled(key: string) {
    await this.pool.query('INSERT INTO schedules(key) VALUES($1) ON CONFLICT DO NOTHING', [key]);
  }
  async sessions(): Promise<string[]> {
    return (await this.pool.query('SELECT id FROM sessions')).rows.map((row) => row.id);
  }
  async cursor(name: string): Promise<number> {
    return Number(
      (await this.pool.query('SELECT value FROM cursors WHERE name=$1', [name])).rows[0]?.value ||
        0,
    );
  }
  async setCursor(name: string, value: number) {
    await this.pool.query(
      'INSERT INTO cursors(name,value) VALUES($1,$2) ON CONFLICT(name) DO UPDATE SET value=GREATEST(cursors.value,excluded.value)',
      [name, value],
    );
  }
  async insertMemory(
    session: string,
    value: MemoryFragment,
    embedding: number[] | null,
    source?: string,
  ) {
    await this.pool.query(
      'INSERT INTO memories(session,text,category,tags,embedding,source) VALUES($1,$2,$3,$4,$5,$6) ON CONFLICT(source) DO NOTHING',
      [
        session,
        value.text,
        value.category,
        JSON.stringify(value.tags),
        embedding ? JSON.stringify(embedding) : null,
        source || null,
      ],
    );
  }
  async searchMemory(
    session: string,
    query: string,
    vector: number[] | undefined,
    categories: string[],
    start?: string,
    end?: string,
  ): Promise<MemoryMatch[]> {
    const client = await this.pool.connect();
    const filter = `session=$1 AND (cardinality($2::text[])=0 OR category=ANY($2)) AND ($3::timestamptz IS NULL OR created >= $3) AND ($4::timestamptz IS NULL OR created <= $4)`;
    const words = query.toLocaleLowerCase().split(/\s+/).filter(Boolean);
    const lexical = `(SELECT count(*)::float FROM unnest($6::text[]) word WHERE strpos(lower(text),word)>0) / GREATEST(cardinality($6::text[]),1)`;
    try {
      await client.query('BEGIN');
      await client.query("SET LOCAL hnsw.iterative_scan = 'strict_order'");
      const { rows } = await client.query(
        `WITH candidates AS MATERIALIZED (
        SELECT * FROM memories WHERE ${filter} AND embedding IS NOT NULL AND $5::vector IS NOT NULL
        ORDER BY embedding::halfvec(${this.dimensions}) <=> $5::halfvec(${this.dimensions}) LIMIT 100
      ), scored AS (
        SELECT text,category,tags,created,CASE WHEN vector_norm(embedding)=0 OR vector_norm($5::vector)=0 THEN 0 ELSE 1-(embedding <=> $5::vector) END AS similarity FROM candidates
        UNION ALL SELECT text,category,tags,created,${lexical} AS similarity FROM memories
        WHERE ${filter} AND (embedding IS NULL OR $5::vector IS NULL)
      ) SELECT * FROM scored WHERE similarity>0.4 ORDER BY similarity DESC LIMIT 10`,
        [
          session,
          categories,
          start || null,
          end || null,
          vector ? JSON.stringify(vector) : null,
          words,
        ],
      );
      await client.query('COMMIT');
      return rows.map((row) => ({
        text: row.text,
        metadata: { category: row.category, tags: row.tags, created_at: row.created.toISOString() },
        similarity: row.similarity,
      }));
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    } finally {
      client.release();
    }
  }
  async memoryCatalog(session: string) {
    const categories = (
      await this.pool.query('SELECT DISTINCT category FROM memories WHERE session=$1', [session])
    ).rows.map((row) => String(row.category));
    const tags = (
      await this.pool.query(
        'SELECT DISTINCT jsonb_array_elements_text(tags) AS tag FROM memories WHERE session=$1',
        [session],
      )
    ).rows.map((row) => String(row.tag));
    return { categories, tags };
  }
  async pendingMemoryMessages(session: string): Promise<PendingMemoryMessage[]> {
    return (
      await this.pool.query(
        "SELECT id,role,text,created FROM messages WHERE role IN ('user','assistant') AND consolidated=0 AND session=$1 ORDER BY id LIMIT 200",
        [session],
      )
    ).rows.map((row) => ({
      id: Number(row.id),
      role: row.role,
      text: row.text,
      created: row.created.toISOString(),
    }));
  }
  async pendingMemorySessions(): Promise<string[]> {
    return (
      await this.pool.query(
        "SELECT DISTINCT session FROM messages WHERE role IN ('user','assistant') AND consolidated=0",
      )
    ).rows.map((row) => row.session);
  }
  async markConsolidated(session: string, ids: number[]) {
    await this.pool.query(
      'UPDATE messages SET consolidated=1 WHERE session=$1 AND id=ANY($2::bigint[])',
      [session, ids],
    );
  }
  async close() {
    if (this.closed) return;
    this.closed = true;
    if (this.lease) {
      const lease = this.lease;
      this.lease = undefined;
      // Destroy rather than pool the connection that holds the lifetime advisory lock.
      lease.release(true);
    }
    await this.pool.end();
  }
}
